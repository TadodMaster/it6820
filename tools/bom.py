#!/usr/bin/env python3
"""Bill of materials: every component of every circuit with its configuration (attributes), as Markdown.

  python tools/bom.py [file.circ] > docs/BOM.md

Only attributes that change the behaviour are listed (labels, fonts and bit assignments of splitters are left out).
"""
import collections
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "RiscVComputer.circ")
text = open(path, encoding="utf-8").read()

SKIP = {"label", "labelfont", "font", "text", "contents", "labelvisible", "appearance", "radix"}
SUBCIRCUITS = set(re.findall(r'  <circuit name="([^"]+)">', text))
ORDER = ["main", "Pipeline", "InstructionDecode", "MainControl", "ImmGen", "RegisterFile", "ALUControl", "ALU", "BranchUnit",
         "Memory", "LoadExtract", "StoreMerge", "ForwardingUnit", "HazardUnit"]


def describe(name, attrs):
    items = [f"{k}={v}" for k, v in attrs.items() if k not in SKIP and not re.fullmatch(r"bit\d+", k)]
    if name == "Splitter":
        items = [i for i in items if not i.startswith("spacing")]
    if name == "Constant":
        if "value" not in attrs:
            items.append("value=0x1 (Logisim does not store the default)")
        if "width" not in attrs:
            items.append("width=1 (default)")
    return ", ".join(items) if items else "default"


print("# Bill of materials\n")
print("Generated by `python tools/bom.py` from `RiscVComputer.circ`; do not edit by hand.  `Tunnel`, `Text` and `Probe`")
print("components are only counted, not listed.  Component settings and the reasons for them are explained in [COMPONENTS.md](COMPONENTS.md).\n")
total = collections.Counter()
for cname in ORDER:
    m = re.search(rf'  <circuit name="{cname}">(.*?)</circuit>', text, re.S)
    if not m:
        continue
    body = m.group(1)
    comps = collections.Counter()
    extra = collections.Counter()
    for c in re.finditer(r'<comp (?:lib="\d+" )?loc="\([^)]*\)" name="([^"]+)"(?:/>|>(.*?)</comp>)', body, re.S):
        name, b = c.group(1), c.group(2) or ""
        attrs = {a.group(1): (a.group(2) if a.group(2) is not None else "<text>")
                 for a in re.finditer(r'<a name="(\w+)"(?: val="([^"]*)"/>|>(.*?)</a>)', b, re.S)}
        if name in ("Tunnel", "Text", "Probe"):
            extra[name] += 1
            continue
        comps[(name, describe(name, attrs))] += 1
        total[name] += 1
    print(f"## {cname}\n")
    pins_in = len(re.findall(r'name="Pin">(?:(?!</comp>).)*?</comp>', body, re.S)) - len(re.findall(r'name="type" val="output"', body))
    pins_out = len(re.findall(r'name="type" val="output"', body))
    print(f"{sum(comps.values())} components, {extra['Tunnel']} tunnels, {extra['Text']} texts, {pins_in} input pins, {pins_out} output pins.\n")
    print("| Count | Component | Configuration |")
    print("|---:|---|---|")
    for (name, cfg), n in sorted(comps.items(), key=lambda x: (x[0][0] in SUBCIRCUITS, x[0][0], x[0][1])):
        if name == "Pin":
            continue
        kind = "sub-circuit" if name in SUBCIRCUITS else name
        label = f"`{name}`" + (" (sub-circuit)" if name in SUBCIRCUITS else "")
        print(f"| {n} | {label} | {cfg} |")
    print()

print("## Totals over the whole project\n")
print("| Component | Count |")
print("|---|---:|")
for name, n in sorted(total.items(), key=lambda x: (-x[1], x[0])):
    if name in SUBCIRCUITS or name == "Pin":
        continue
    print(f"| {name} | {n} |")
print("\n(The counts add up the contents of every circuit once; the single-cycle CPU and the pipeline each contain their own copies of the sub-circuit *instances*.)")
